"""Manual local acceptance runner; no model credentials, no seed or clock override."""

import json
import os
import subprocess
import sys
from contextlib import ExitStack

import httpx

from scripts.start_demo import (
    ROOT,
    backend_environment,
    frontend_environment,
    port_available,
    wait_ready,
)


def main():
    out = ROOT / "logs/refactor"
    out.mkdir(parents=True, exist_ok=True)
    ports = (18010, 18510)
    assert all(port_available(p) for p in ports), "Test ports occupied; no existing process stopped"
    env = frontend_environment(os.environ, ports[0])
    env["DATABASE_URL"] = backend_environment(ROOT / ".env").get(
        "DATABASE_URL", "sqlite:///./data/componentmatch.db"
    )
    env["COMPONENTMATCH_OFFLINE_UI_TEST"] = "1"
    children = []
    try:
        with ExitStack() as stack:
            for name, args, child_env in (
                (
                    "backend",
                    [
                        "-m",
                        "uvicorn",
                        "tests.phase5_browser_server:app",
                        "--host",
                        "127.0.0.1",
                        "--port",
                        "18010",
                    ],
                    env,
                ),
                (
                    "frontend",
                    [
                        "-m",
                        "streamlit",
                        "run",
                        "frontend/app.py",
                        "--server.address",
                        "127.0.0.1",
                        "--server.port",
                        "18510",
                        "--server.headless",
                        "true",
                    ],
                    frontend_environment(env, ports[0]),
                ),
            ):
                log = stack.enter_context((out / f"{name}.log").open("w", encoding="utf-8"))
                children.append(
                    subprocess.Popen(
                        [
                            str(ROOT / ".venv-frontend/Scripts/python.exe")
                            if name == "frontend"
                            else sys.executable,
                            *args,
                        ],
                        cwd=ROOT,
                        env=child_env,
                        stdout=log,
                        stderr=subprocess.STDOUT,
                        creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
                    )
                )
            wait_ready(children[0], "http://127.0.0.1:18010/health", json_response=True)
            wait_ready(children[1], "http://127.0.0.1:18510/_stcore/health")
            with httpx.Client(
                base_url="http://127.0.0.1:18010", trust_env=False, timeout=30
            ) as client:
                base = {
                    "part_number": "LM358DR",
                    "manufacturer": "TI",
                    "quantity": 1000,
                    "delivery_mode": "within_days",
                    "max_delivery_days": 7,
                    "max_unit_price_cents": 120,
                    "total_budget_cents": 120000,
                    "required_certifications": ["ISO9001"],
                }
                results = {}
                for name, changes in {
                    "balanced": {},
                    "cost": {"preference_profile": "cost"},
                    "quality": {"preference_profile": "quality"},
                    "strict": {"max_unit_price_cents": 1},
                    "stock": {"quantity": 1000000000},
                    "budget": {"total_budget_cents": 1},
                }.items():
                    response = client.post("/api/v1/matches", json={"requirement": base | changes})
                    assert response.status_code == 200
                    results[name] = response.json()
                (out / "real_clock_rules.json").write_text(
                    json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8"
                )
            # Requests after this point are generated by the actual Streamlit browser.
            with httpx.Client(trust_env=False) as client:
                prior_count = len(
                    client.get("http://127.0.0.1:18010/__test__/calls").json()["requests"]
                )
            browser = subprocess.run(
                [
                    "uv",
                    "--cache-dir",
                    ".uv-cache",
                    "tool",
                    "run",
                    "--from",
                    "playwright",
                    "python",
                    "tests/phase5_browser_check.py",
                ],
                cwd=ROOT,
                env=frontend_environment(os.environ),
            )
            assert browser.returncode == 0, "Browser check failed; see screenshots/logs"
            with httpx.Client(trust_env=False) as client:
                records = client.get("http://127.0.0.1:18010/__test__/calls").json()
            (out / "http_call_audit.json").write_text(
                json.dumps(records, indent=2), encoding="utf-8"
            )
            assert records["paid_attempts"] == 0
            browser_requests = records["requests"][prior_count:]
            assert browser_requests and all(
                r["path"] == "/api/v1/agent/matches" for r in browser_requests
            )
            rules = [r for r in records["requests"] if r["path"] == "/api/v1/matches"]
            assert rules and all(
                r["mock_model_calls"] == 0 and not r["authorization_present"] for r in rules
            )
            print(
                json.dumps(
                    {
                        "backend_structured_http_requests": len(rules),
                        "browser_agent_requests": len(browser_requests),
                        "browser_structured_requests": 0,
                        "rule_model_calls": 0,
                        "paid_attempts": 0,
                        "backend_health": True,
                        "frontend_health": True,
                    }
                )
            )
    finally:
        for child in reversed(children):
            if child.poll() is None:
                if os.name == "nt":
                    subprocess.run(
                        ["taskkill", "/PID", str(child.pid), "/T", "/F"],
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                        check=False,
                    )
                else:
                    child.terminate()
                child.wait(timeout=10)
        released = {p: port_available(p) for p in ports}
        (out / "ports.json").write_text(json.dumps(released), encoding="utf-8")
        assert all(released.values())


if __name__ == "__main__":
    main()
